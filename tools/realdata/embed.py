"""
Embed the real-player CSV in the game build (src/engine/data/realPlayers.generated.ts).
The artifact's CSP blocks outside requests, so the data ships with the build and is refreshed monthly.

Usage: python3 tools/realdata/embed.py players-YYYY-MM-DD.csv YYYY-MM-DD
"""
import json, os, sys

CSV, DATE = sys.argv[1], sys.argv[2]
text = open(CSV, encoding='utf-8').read().replace('\r\n', '\n')
out = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'engine', 'data', 'realPlayers.generated.ts')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/realdata/embed.py. Do not edit by hand; see tools/realdata/README.md.\n')
    f.write('// Rosters and team strength: Valve Counter-Strike Regional Standings. Countries, ages, roles: Liquipedia (CC BY-SA 3.0).\n')
    f.write('// Ratings are Clutch Manager\'s own game numbers, not official statistics. This file is shared under CC BY-SA 3.0.\n')
    f.write(f'export const REAL_SNAPSHOT_DATE = {json.dumps(DATE)};\n')
    f.write(f'export const REAL_PLAYERS_CSV = {json.dumps(text, ensure_ascii=False)};\n')
print('wrote', os.path.normpath(out), len(text), 'chars')
