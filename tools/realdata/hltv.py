"""
HLTV player statistics for the real-pro dataset, from a stats page the user saved in a browser.

HLTV has no public API and blocks automated access, so this reads a page saved by hand
(https://www.hltv.org/stats/players, Ctrl+S). It writes src/engine/data/hltvStats.generated.ts:
handle -> maps, rounds, K-D difference, K/D and HLTV rating. Used in a free, non-commercial
university project only; the game's own player ratings are not changed by it.

Usage: python3 hltv.py "<saved page>.html" YYYY-MM-DD
"""
import csv, html, io, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
page, snapshot = sys.argv[1], sys.argv[2]
s = open(page, encoding='utf8', errors='replace').read()
table = s[s.index('<table class="stats-table player-ratings-table'):]
table = table[:table.index('</table>')]
rows = re.findall(r'<tr>(.*?)</tr>', table, re.S)
num = lambda x: float(x.replace(',', '').replace('+', ''))
stats = {}
for r in rows:
    m = re.search(r'/stats/players/(\d+)/[^"]*"[^>]*>([^<]+)</a>', r)
    team = re.search(r'class="teamCol" data-sort="([^"]*)"', r)
    cells = re.findall(r'<td class="(statsDetail[^"]*|kdDiffCol[^"]*|ratingCol[^"]*)"[^>]*>([^<]*)</td>', r)
    if not m or len(cells) < 5:
        continue
    vals = [c[1].strip() for c in cells]
    handle = html.unescape(m.group(2)).strip()
    entry = {'id': int(m.group(1)), 'team': html.unescape(team.group(1)) if team else '', 'maps': int(num(vals[0])), 'rounds': int(num(vals[1])),
             'diff': int(num(vals[2])), 'kd': num(vals[3]), 'rating': num(vals[4])}
    key = handle.lower()
    # Same handle twice: keep the player with more maps (the established pro).
    if key not in stats or stats[key]['maps'] < entry['maps']:
        stats[key] = entry

# Keep only the players in the game's dataset.
gen = open(os.path.join(ROOT, 'src', 'engine', 'data', 'realPlayers.generated.ts'), encoding='utf8').read()
csv_text = json.loads(re.search(r'REAL_PLAYERS_CSV = (".*?");\n', gen, re.S).group(1))
ours = [row['handle'] for row in csv.DictReader(io.StringIO(csv_text))]
out = {h: stats[h.lower()] for h in ours if h.lower() in stats}
missing = [h for h in ours if h.lower() not in stats]
dst = os.path.join(ROOT, 'src', 'engine', 'data', 'hltvStats.generated.ts')
with open(dst, 'w', encoding='utf8', newline='\n') as f:
    f.write('// Generated by tools/realdata/hltv.py from a saved HLTV.org stats page. Do not edit by hand.\n')
    f.write('// Free, non-commercial university project; HLTV statistics belong to HLTV.org.\n')
    f.write('export interface HltvLine { id: number; team: string; maps: number; rounds: number; diff: number; kd: number; rating: number }\n')
    f.write(f'export const HLTV_SNAPSHOT = {json.dumps(snapshot)};\n')
    f.write('export const HLTV_STATS: Record<string, HltvLine> = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(f'{len(rows)} rows on the page, {len(out)} of {len(ours)} game players matched; missing e.g. {missing[:15]}')
